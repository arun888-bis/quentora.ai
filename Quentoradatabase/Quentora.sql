-- ============================================
-- QUENTORA PostgreSQL DATABASE SCHEMA
--
-- ============================================


-- ============================================
-- 1. ADMINS
-- ============================================

CREATE TABLE admins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50),
    password VARCHAR(50),
    role VARCHAR(30) DEFAULT 'administrator',
    name VARCHAR(100) DEFAULT 'Admin'
);


-- ============================================
-- 2. CLASSES
-- Depends on admins
-- ============================================

CREATE TABLE classes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    created_by INTEGER,

    CONSTRAINT classes_created_by_fkey
        FOREIGN KEY (created_by)
        REFERENCES admins(id)
);


-- ============================================
-- 3. BOOKS
-- Depends on classes
-- ============================================

CREATE TABLE books (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100),
    class_id INTEGER,
    is_published BOOLEAN DEFAULT FALSE,

    CONSTRAINT books_class_id_fkey
        FOREIGN KEY (class_id)
        REFERENCES classes(id)
);


CREATE INDEX idx_books_class_id
ON books(class_id);


-- ============================================
-- 4. STUDENTS
-- Depends on classes
-- ============================================

CREATE TABLE students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    roll_number VARCHAR(50),
    class_id INTEGER,
    username VARCHAR(50),
    password VARCHAR(50),

    CONSTRAINT students_class_id_fkey
        FOREIGN KEY (class_id)
        REFERENCES classes(id)
);


CREATE INDEX idx_students_class_id
ON students(class_id);


-- ============================================
-- 5. ASSESSMENTS
-- Depends on books and classes
-- ============================================

CREATE TABLE assessments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INTEGER NOT NULL,
    class_id INTEGER,
    title VARCHAR(180) NOT NULL,
    description TEXT,
    source_type VARCHAR(30) DEFAULT 'manual',
    is_published BOOLEAN DEFAULT TRUE,
    created_by INTEGER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    assessment_type VARCHAR(50) DEFAULT 'quiz',

    CONSTRAINT fk_assessments_book
        FOREIGN KEY (book_id)
        REFERENCES books(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_assessments_class
        FOREIGN KEY (class_id)
        REFERENCES classes(id)
        ON DELETE SET NULL
);


CREATE INDEX idx_assessments_book_id
ON assessments(book_id);

CREATE INDEX idx_assessments_class_id
ON assessments(class_id);

CREATE INDEX idx_assessments_title
ON assessments(title);


-- ============================================
-- 6. MCQS
-- Depends on classes, books and assessments
-- ============================================

CREATE TABLE mcqs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question TEXT,
    option_a VARCHAR(255),
    option_b VARCHAR(255),
    option_c VARCHAR(255),
    option_d VARCHAR(255),
    correct_option CHAR(1),
    model_justification TEXT,
    class_id INTEGER,
    book_id INTEGER,
    is_published BOOLEAN DEFAULT FALSE,
    assessment_id INTEGER,
    source_type VARCHAR(30) DEFAULT 'manual',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    -- Your newly added difficulty feature
    difficulty VARCHAR(20) DEFAULT 'Medium',

    CONSTRAINT fk_mcqs_assessment
        FOREIGN KEY (assessment_id)
        REFERENCES assessments(id)
        ON DELETE SET NULL,

    CONSTRAINT mcqs_class_id_fkey
        FOREIGN KEY (class_id)
        REFERENCES classes(id),

    CONSTRAINT mcqs_book_id_fkey
        FOREIGN KEY (book_id)
        REFERENCES books(id)
);


CREATE INDEX idx_mcqs_class_id
ON mcqs(class_id);

CREATE INDEX idx_mcqs_book_id
ON mcqs(book_id);

CREATE INDEX idx_mcqs_assessment_id
ON mcqs(assessment_id);


-- ============================================
-- 7. STUDENT ASSESSMENT ATTEMPTS
-- Depends on students and assessments
-- ============================================

CREATE TABLE student_assessment_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    assessment_id INTEGER NOT NULL,
    attempt_no INTEGER DEFAULT 1,
    total_marks REAL DEFAULT 0,
    total_questions INTEGER DEFAULT 0,
    percentage REAL DEFAULT 0,
    status VARCHAR(30) DEFAULT 'submitted',
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_attempt_assessment
        FOREIGN KEY (assessment_id)
        REFERENCES assessments(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_attempt_student
        FOREIGN KEY (student_id)
        REFERENCES students(id)
        ON DELETE CASCADE
);


CREATE INDEX idx_attempt_student
ON student_assessment_attempts(student_id);

CREATE INDEX idx_attempt_assessment
ON student_assessment_attempts(assessment_id);


-- ============================================
-- 8. RESULTS
-- Depends on students, mcqs and attempts
-- ============================================

CREATE TABLE results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER,
    mcq_id INTEGER,
    selected_option CHAR(1),
    justification TEXT,
    marks REAL,
    feedback VARCHAR(255),
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempt_id INTEGER,
    assessment_id INTEGER,
    llm_feedback TEXT,

    CONSTRAINT fk_results_attempt
        FOREIGN KEY (attempt_id)
        REFERENCES student_assessment_attempts(id)
        ON DELETE SET NULL,

    CONSTRAINT results_student_id_fkey
        FOREIGN KEY (student_id)
        REFERENCES students(id),

    CONSTRAINT results_mcq_id_fkey
        FOREIGN KEY (mcq_id)
        REFERENCES mcqs(id)
);


CREATE INDEX idx_results_student_id
ON results(student_id);

CREATE INDEX idx_results_mcq_id
ON results(mcq_id);

CREATE INDEX idx_results_attempt_id
ON results(attempt_id);

CREATE INDEX idx_results_assessment_id
ON results(assessment_id);

